import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';

const base='http://127.0.0.1:8768';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const goal=`界面体验验证 ${Date.now()}`;
try{
 await page.goto(base);
 await page.getByRole('button',{name:'新建对话'}).click();
 await page.locator('#new-research').fill(goal);
 await page.getByRole('button',{name:'创建研究'}).click();
 await page.getByRole('heading',{name:goal}).waitFor();
 await page.getByRole('button',{name:'上传资料'}).first().click();
 await page.locator('#upload-file').setInputFiles({name:'产品调研摘要.txt',mimeType:'text/plain',buffer:Buffer.from('Synthetic product research note for isolated UI review. No private information.\n')});
 await page.getByRole('dialog',{name:'上传资料'}).getByRole('button',{name:'上传资料'}).click();
 await page.getByRole('button',{name:'产品调研摘要.txt'}).waitFor();
 await page.getByRole('button',{name:'产品调研摘要.txt'}).click();
 await page.getByRole('link',{name:'查看或下载原件'}).waitFor();
 await page.getByRole('button',{name:'打开主对话'}).click();
 await page.getByLabel('发送到此节点').fill('请概述这项研究的下一步。');
 await page.getByRole('button',{name:'发送并执行回复'}).click();
 await page.getByText('Scripted chat control reply.',{exact:false}).first().waitFor({timeout:20000});
 await page.screenshot({path:'frontend/preview-chat.png'});
 await page.getByRole('button',{name:'创建分支'}).first().click();
 await page.getByLabel('分支截止消息').selectOption({index:2});
 await page.getByLabel('分支目标').fill('资料整理分支');
 await page.getByRole('button',{name:'创建分支'}).last().click();
 await page.getByRole('heading',{name:'资料整理分支'}).waitFor();
 await page.getByRole('button',{name:'派发专家'}).last().click();
 await page.locator('#task-request').fill('整理合成资料中的要点');
 await page.getByRole('dialog',{name:'派发专家任务'}).locator('input[type=checkbox]').first().check();
 await page.getByRole('button',{name:'创建并派发'}).click();
 await page.getByRole('heading',{name:'整理合成资料中的要点'}).waitFor({timeout:20000});
 await page.getByRole('button',{name:'返回 Flow'}).click();
 await page.getByRole('heading',{name:goal}).waitFor();
 await page.locator('.task-body .agent-node').first().waitFor();
 await page.screenshot({path:'frontend/preview-overview.png'});
 await page.getByRole('button',{name:'打开主对话'}).click();
 await page.getByText('Scripted chat control reply.',{exact:false}).first().waitFor();
 await page.getByRole('button',{name:'返回 Flow'}).click();
 await page.reload();
 await page.getByRole('heading',{name:goal}).waitFor();
 assert.equal(await page.locator('.task-card').count(),1);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,goal,errors,screenshots:['frontend/preview-overview.png','frontend/preview-chat.png']}));
}catch(error){console.error((await page.locator('body').innerText()).slice(-5000));console.error(errors);throw error}finally{await browser.close()}
