from typing import Protocol, Callable
from .snapshots import Resource, SourceSnapshot, ResourceIngestion, ParseResult, ParsedContent


class BlobStore(Protocol):
    def put(self, content: bytes) -> str: ...
    def get(self, digest: str) -> bytes: ...


class Parser(Protocol):
    key: str
    def parse(self, content: bytes, media_type: str, progress: Callable[[str], None]) -> ParsedContent: ...


class ResourceRepository(Protocol):
    def register(self, resource: Resource, snapshot: SourceSnapshot, ingestion: ResourceIngestion, parse: ParseResult) -> None: ...
    def resource(self, resource_id: str) -> Resource: ...
    def snapshot(self, snapshot_id: str) -> SourceSnapshot: ...
    def parse(self, parse_id: str) -> ParseResult: ...
    def save_parse(self, result: ParseResult) -> None: ...
    def cached_parse(self, digest: str, parser_key: str) -> ParseResult | None: ...
    def ingestions(self, scope_id: str) -> tuple[ResourceIngestion, ...]: ...
    def ingestion(self, snapshot_id: str) -> ResourceIngestion: ...
