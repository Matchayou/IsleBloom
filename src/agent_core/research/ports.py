from typing import Protocol
from .models import Research, ResearchNode, NodeRun, NodeResultVersion, CommandRecord


class ResearchRepository(Protocol):
    """Caller owns the transaction. No method reads another module's tables."""
    def research(self, key: str) -> Research: ...
    def node(self, key: str) -> ResearchNode: ...
    def command(self, key: str) -> CommandRecord | None: ...
    def run(self, key: str) -> NodeRun | None: ...
    def result(self, key: str) -> NodeResultVersion: ...
    def list_nodes(self, key: str) -> list[ResearchNode]: ...
    def list_runs(self, key: str) -> list[NodeRun]: ...
    def list_results(self, key: str) -> list[NodeResultVersion]: ...
    def inputs(self, key: str) -> tuple[str, ...]: ...
    def create_research(self, value: Research) -> None: ...
    def admit_plan(self, plan) -> bool: ...
    def create_node(self, value: ResearchNode) -> None: ...
    def create_command(self, value: CommandRecord) -> None: ...
    def create_run(self, value: NodeRun) -> None: ...
    def save_node(self, value: ResearchNode, expected_revision: int) -> None: ...
    def save_command(self, value: CommandRecord) -> None: ...
    def publish(self, value: NodeResultVersion, dependencies: tuple[str, ...]) -> None: ...

    def proposal(self, key): ...
    def proposal_request(self, research_id, request_id): ...
    def list_proposals(self, research_id): ...
    def create_proposal(self, value): ...
    def save_proposal(self, value, expected_revision): ...
