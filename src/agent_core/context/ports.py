from typing import Protocol
from .scopes import RunScope
from .mounts import ContextSnapshot


class ContextRepository(Protocol):
    def scope(self, key: str) -> RunScope: ...
    def save_scope(self, scope: RunScope, expected_version: int | None) -> None: ...
    def save_snapshot(self, snapshot: ContextSnapshot) -> None: ...
    def snapshot(self, run_id: str) -> ContextSnapshot: ...
